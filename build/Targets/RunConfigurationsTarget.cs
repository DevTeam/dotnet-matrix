using System.Xml.Linq;
using Matrix;

namespace Build.Targets;

internal sealed class RunConfigurationsTarget(IBuildPaths buildPaths)
    : IRunConfigurationsTarget
{
    private const string GeneratedMarker = "Generated by dotnet-matrix";
    private static readonly string TargetFramework =
        new DirectoryInfo(AppContext.BaseDirectory).Name;

    public int Run(IReadOnlyList<DiscoveredMatrixModule> modules)
    {
        var directory = Path.Combine(buildPaths.SolutionDirectory, ".run");
        Directory.CreateDirectory(directory);
        DeleteGeneratedConfigurations(directory, modules);

        var configurations = CreateConfigurations(modules).ToArray();
        foreach (var configuration in configurations)
        {
            var path = Path.Combine(directory, $"{ToFileName(configuration.Name)}.run.xml");
            File.WriteAllText(path, CreateDocument(configuration) + Environment.NewLine);
        }

        Info($"Run configurations: {configurations.Length} generated.");
        return 0;
    }

    private static IEnumerable<RunConfiguration> CreateConfigurations(
        IReadOnlyList<DiscoveredMatrixModule> modules)
    {
        yield return new RunConfiguration(
            "Generate Run Configurations",
            MatrixNames.RunConfigurationsCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.MetadataConfiguration,
            MatrixNames.MetadataCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.BuildWebConfiguration,
            MatrixNames.BuildWebCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.RenderReportsConfiguration,
            MatrixNames.RenderReportsCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.ReadmeConfiguration,
            MatrixNames.ReadmeCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.PrepareCommitConfiguration,
            MatrixNames.PrepareCommitCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.FinalizeCommitConfiguration,
            MatrixNames.FinalizeCommitCommand,
            null);
        yield return new RunConfiguration(
            MatrixNames.ReproduceConfiguration,
            MatrixNames.ReproduceCommand,
            null);

        foreach (var module in modules)
        {
            var updateLibraryCommand = MatrixNames.UpdateLibraryCommand(module.Metadata);
            foreach (var library in module.Metadata.Libraries)
            {
                yield return new RunConfiguration(
                    MatrixNames.UpdateLibraryConfiguration(module.Metadata, library.Id),
                    $"{updateLibraryCommand} --library {library.Id}",
                    module.Metadata.Name);
            }

            foreach (var mode in Enum.GetValues<MatrixMode>())
            {
                var command = MatrixNames.Command(module.Metadata, mode);
                foreach (var library in module.Metadata.Libraries)
                {
                    yield return new RunConfiguration(
                        MatrixNames.Configuration(module.Metadata, mode, library.Id),
                        $"{command} --libraries {library.Id}",
                        module.Metadata.Name);
                }

                yield return new RunConfiguration(
                    MatrixNames.Configuration(module.Metadata, mode, "All"),
                    command,
                    module.Metadata.Name);
            }
        }
    }

    private static void DeleteGeneratedConfigurations(
        string directory,
        IReadOnlyList<DiscoveredMatrixModule> modules)
    {
        var commands = modules
            .SelectMany(module => Enum
                .GetValues<MatrixMode>()
                .Select(mode => MatrixNames.Command(module.Metadata, mode))
                .Append(MatrixNames.UpdateLibraryCommand(module.Metadata)))
            .Append(MatrixNames.RunConfigurationsCommand)
            .Append(MatrixNames.MetadataCommand)
            .Append(MatrixNames.RenderReportsCommand)
            .Append(MatrixNames.ReadmeCommand)
            .Append(MatrixNames.PrepareCommitCommand)
            .Append(MatrixNames.FinalizeCommitCommand)
            .Append(MatrixNames.ReproduceCommand)
            .Append(MatrixNames.CiReportsCommand)
            .Append(MatrixNames.BuildWebCommand)
            .ToArray();
        foreach (var path in Directory.EnumerateFiles(directory, "*.run.xml"))
        {
            var document = XDocument.Load(path);
            var generated = document
                .Nodes()
                .OfType<XComment>()
                .Any(comment => comment.Value.Contains(GeneratedMarker, StringComparison.Ordinal));
            var arguments = document
                .Descendants("option")
                .SingleOrDefault(option => (string?)option.Attribute("name") == "PROGRAM_PARAMETERS")
                ?.Attribute("value")
                ?.Value;
            if (generated || commands.Any(command =>
                    arguments == command
                    || arguments?.StartsWith($"{command} ", StringComparison.Ordinal) == true))
            {
                File.Delete(path);
            }
        }
    }

    private static XDocument CreateDocument(RunConfiguration configuration) =>
        new(
            new XComment($" {GeneratedMarker} "),
            new XElement(
                "component",
                new XAttribute("name", "ProjectRunConfigurationManager"),
                new XElement(
                    "configuration",
                    new XAttribute("default", "false"),
                    new XAttribute("name", configuration.Name),
                    new XAttribute("type", "DotNetProject"),
                    new XAttribute("factoryName", ".NET Project"),
                    configuration.FolderName is null
                        ? null
                        : new XAttribute("folderName", configuration.FolderName),
                    Option("EXE_PATH", $"$PROJECT_DIR$/build/bin/Debug/{TargetFramework}/build.exe"),
                    Option("PROGRAM_PARAMETERS", configuration.Arguments),
                    Option("WORKING_DIRECTORY", "$PROJECT_DIR$"),
                    Option("PASS_PARENT_ENVS", "1"),
                    Option("USE_EXTERNAL_CONSOLE", "0"),
                    Option("ENV_FILE_PATHS", string.Empty),
                    Option("REDIRECT_INPUT_PATH", string.Empty),
                    Option("PTY_MODE", "Auto"),
                    Option("USE_MONO", "0"),
                    Option("RUNTIME_ARGUMENTS", string.Empty),
                    Option("AUTO_ATTACH_CHILDREN", "0"),
                    Option("MIXED_MODE_DEBUG", "0"),
                    Option("PROJECT_PATH", "$PROJECT_DIR$/build/build.csproj"),
                    Option("PROJECT_EXE_PATH_TRACKING", "1"),
                    Option("PROJECT_ARGUMENTS_TRACKING", "1"),
                    Option("PROJECT_WORKING_DIRECTORY_TRACKING", "0"),
                    Option("PROJECT_KIND", "DotNetCore"),
                    Option("PROJECT_TFM", TargetFramework),
                    new XElement(
                        "method",
                        new XAttribute("v", "2"),
                        new XElement("option", new XAttribute("name", "Build"))))));

    private static XElement Option(string name, string value) =>
        new(
            "option",
            new XAttribute("name", name),
            new XAttribute("value", value));

    private static string ToFileName(string value)
    {
        var invalidCharacters = Path.GetInvalidFileNameChars();
        return string.Concat(value.Select(character =>
            invalidCharacters.Contains(character) ? '_' : character));
    }

}
